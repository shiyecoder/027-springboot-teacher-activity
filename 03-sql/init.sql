CREATE TABLE sys_dict (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  dict_type VARCHAR(40) NOT NULL COMMENT '字典类型',
  dict_label VARCHAR(60) NOT NULL COMMENT '标签',
  dict_value VARCHAR(40) NOT NULL COMMENT '值',
