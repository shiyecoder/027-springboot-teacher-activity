CREATE TABLE sys_org (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  org_name VARCHAR(64) NOT NULL COMMENT '组织名称',
  org_code VARCHAR(32) NOT NULL COMMENT '组织编码',
  parent_id BIGINT DEFAULT 0 COMMENT '上级组织',
  leader VARCHAR(32) DEFAULT NULL COMMENT '负责人',
  sort INT DEFAULT 0 COMMENT '排序',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB COMMENT='组织架构';

CREATE TABLE sys_role (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  role_name VARCHAR(64) NOT NULL COMMENT '角色名称',
  role_code VARCHAR(32) NOT NULL COMMENT '角色编码',
  data_scope VARCHAR(20) NOT NULL DEFAULT 'SELF' COMMENT '数据范围 SELF/DEPT/ORG/ALL',
  remark VARCHAR(200) DEFAULT NULL COMMENT '说明',
  status TINYINT DEFAULT 1 COMMENT '1启用 0停用',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  UNIQUE KEY uk_role_code (role_code)
) ENGINE=InnoDB COMMENT='角色';

CREATE TABLE sys_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  username VARCHAR(50) NOT NULL COMMENT '登录账号',
  password VARCHAR(100) NOT NULL COMMENT 'BCrypt 密码',
  real_name VARCHAR(50) NOT NULL COMMENT '姓名',
  avatar VARCHAR(200) DEFAULT NULL COMMENT '头像相对路径',
  phone VARCHAR(20) DEFAULT NULL COMMENT '手机号',
  email VARCHAR(80) DEFAULT NULL COMMENT '邮箱',
  org_id BIGINT DEFAULT NULL COMMENT '所属组织',
  role_id BIGINT DEFAULT NULL COMMENT '角色',
  status TINYINT DEFAULT 1 COMMENT '1启用 0停用',
  login_fail INT DEFAULT 0 COMMENT '连续登录失败次数',
  lock_until DATETIME DEFAULT NULL COMMENT '锁定截止时间',
  last_login DATETIME DEFAULT NULL COMMENT '最后登录',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  deleted TINYINT DEFAULT 0 COMMENT '逻辑删除',
  UNIQUE KEY uk_username (username),
  KEY idx_user_org (org_id)
) ENGINE=InnoDB COMMENT='用户';

CREATE TABLE sys_menu (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  parent_id BIGINT DEFAULT 0 COMMENT '上级菜单',
  menu_name VARCHAR(64) NOT NULL COMMENT '菜单名称',
